import os
import psycopg
from psycopg.rows import dict_row


def get_connection():
    """Open a PostgreSQL connection using Render's DATABASE_URL."""
    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is missing. Add the Supabase Session pooler URL "
            "to the Render service Environment settings."
        )
    return psycopg.connect(database_url, row_factory=dict_row)


def init_db():
    """Create SecureVault tables if they do not already exist."""
    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is missing. Add the Supabase Session pooler URL "
            "to the Render service Environment settings."
        )

    with psycopg.connect(database_url, row_factory=dict_row) as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                password TEXT NOT NULL
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS files (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                owner_id BIGINT NOT NULL REFERENCES users(id),
                original_name TEXT NOT NULL,
                stored_name TEXT NOT NULL,
                uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
